export function getSetBannerArt(setCode: string): string {
  const upper = setCode.toUpperCase();
  if (ARENA_SET_ART[upper]?.artCrop) return ARENA_SET_ART[upper].artCrop;
  const clean = upper.replace(/^Y/, '');
  if (ARENA_SET_ART[clean]?.artCrop) return ARENA_SET_ART[clean].artCrop;
  return DEFAULT_BANNER;
}

export function getSetIconSvgUri(setCode: string): string {
  const clean = setCode.toLowerCase().replace(/^y/, '');
  return 'https://svgs.scryfall.io/sets/' + clean + '.svg';
}
